-- ---------- Client terms acceptance ------------------------------------------------------------
alter table public.companies add column if not exists terms_accepted_at timestamptz;

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  r text := coalesce(m->>'role', 'expert');
begin
  if r not in ('expert','company') then r := 'expert'; end if;
  insert into public.profiles (id, role, email, full_name, country)
  values (new.id, r, new.email, m->>'full_name', m->>'country');
  if r = 'expert' then
    insert into public.experts (id, field, years_experience, linkedin, rate_expectation, bio, referral_code, referred_by)
    values (
      new.id,
      m->>'field',
      case when (m->>'years') ~ '^\d{1,2}$' then (m->>'years')::int end,
      m->>'linkedin',
      case when (m->>'rate') ~ '^\d{1,4}(\.\d+)?$' then (m->>'rate')::numeric end,
      m->>'bio',
      substr(replace(new.id::text, '-', ''), 1, 8),
      nullif(m->>'ref', '')
    );
  else
    insert into public.companies (id, company_name, website, terms_accepted_at)
    values (new.id, m->>'company_name', m->>'website', case when m->>'terms' = 'accepted' then now() end);
  end if;
  return new;
end $$;

create or replace function public.accept_client_terms() returns void
language sql security definer set search_path = public as $$
  update companies set terms_accepted_at = now() where id = auth.uid() and terms_accepted_at is null;
$$;
revoke all on function public.accept_client_terms() from public, anon;
grant execute on function public.accept_client_terms() to authenticated;

