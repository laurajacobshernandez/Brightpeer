-- ---------- Visitor statistics (no cookies, no IP, no personal data) ---------------------------
create table if not exists public.page_views (
  id bigint generated always as identity primary key,
  at timestamptz not null default now(),
  path text not null check (length(path) <= 120),
  referrer text check (length(referrer) <= 120),
  lang text check (length(lang) <= 10),
  device text check (device in ('mobile','tablet','desktop')),
  entry boolean not null default false   -- first page of a visit (no visitor id is stored anywhere)
);
alter table public.page_views enable row level security;
drop policy if exists p_pv_insert on public.page_views;
create policy p_pv_insert on public.page_views for insert to anon, authenticated with check (at > now() - interval '1 minute');
drop policy if exists p_pv_select on public.page_views;
create policy p_pv_select on public.page_views for select using (public.is_admin());
grant insert on public.page_views to anon, authenticated;
grant select on public.page_views to authenticated;
create index if not exists page_views_at on public.page_views (at);

create or replace function public.admin_visitor_stats(p_days int default 30) returns json
language plpgsql stable security definer set search_path = public as $$
declare since timestamptz := now() - make_interval(days => greatest(1, least(p_days, 400)));
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  return json_build_object(
    'views', (select count(*) from page_views where at >= since),
    'visits', (select count(*) from page_views where at >= since and entry),
    'today', (select count(*) from page_views where at >= date_trunc('day', now()) and entry),
    'by_day', (select coalesce(json_agg(x order by x.day), '[]') from (select date_trunc('day', at)::date as day, count(*) as views, count(*) filter (where entry) as visits from page_views where at >= since group by 1) x),
    'pages', (select coalesce(json_agg(x), '[]') from (select path, count(*) as views from page_views where at >= since group by 1 order by 2 desc limit 15) x),
    'referrers', (select coalesce(json_agg(x), '[]') from (select coalesce(referrer, 'direct') as referrer, count(*) as visits from page_views where at >= since and entry group by 1 order by 2 desc limit 10) x),
    'devices', (select coalesce(json_agg(x), '[]') from (select device, count(*) as visits from page_views where at >= since and entry group by 1 order by 2 desc) x),
    'langs', (select coalesce(json_agg(x), '[]') from (select lang, count(*) as visits from page_views where at >= since and entry group by 1 order by 2 desc limit 8) x)
  );
end $$;
revoke all on function public.admin_visitor_stats(int) from public, anon;
grant execute on function public.admin_visitor_stats(int) to authenticated;

-- ---------- Anonymous expert profiles proposed to companies -----------------------------------
create table if not exists public.request_candidates (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests(id) on delete cascade,
  expert_id uuid not null references public.experts(id) on delete cascade,
  status text not null default 'proposed' check (status in ('proposed','interested','declined')),
  admin_note text check (length(admin_note) <= 1000),
  company_note text check (length(company_note) <= 1000),
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  unique (request_id, expert_id)
);
alter table public.request_candidates enable row level security;
drop policy if exists p_rc_admin on public.request_candidates;
create policy p_rc_admin on public.request_candidates for all using (public.is_admin()) with check (public.is_admin());

create or replace function public.company_candidates()
returns table(id uuid, request_id uuid, request_field text, code text, field text, years int, headline text, skills text,
              country text, test_pct int, interview_score int, status text, admin_note text, company_note text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select rc.id, rc.request_id, r.field, 'Expert ' || upper(left(rc.id::text, 4)), e.field, e.years_experience,
         e.headline, e.skills, p.country,
         (select max(round(100.0 * ta.mc_score / nullif(ta.mc_max, 0)))::int from test_attempts ta where ta.expert_id = e.id and ta.status = 'passed'),
         (select i.score from interviews i where i.expert_id = e.id and i.status = 'reviewed'),
         rc.status, rc.admin_note, rc.company_note, rc.created_at
  from request_candidates rc
  join requests r on r.id = rc.request_id
  join experts e on e.id = rc.expert_id
  join profiles p on p.id = e.id
  where r.company_id = auth.uid()
  order by rc.created_at desc;
$$;
revoke all on function public.company_candidates() from public, anon;
grant execute on function public.company_candidates() to authenticated;

create or replace function public.respond_candidate(p_id uuid, p_interested boolean, p_note text default null) returns text
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from request_candidates rc join requests r on r.id = rc.request_id where rc.id = p_id and r.company_id = auth.uid()) then
    raise exception 'not found';
  end if;
  update request_candidates set status = case when p_interested then 'interested' else 'declined' end,
         company_note = nullif(left(trim(coalesce(p_note, '')), 1000), ''), responded_at = now()
   where id = p_id;
  return case when p_interested then 'interested' else 'declined' end;
end $$;
revoke all on function public.respond_candidate(uuid, boolean, text) from public, anon;
grant execute on function public.respond_candidate(uuid, boolean, text) to authenticated;

-- ---------- Referral bonus tracking -----------------------------------------------------------
create table if not exists public.referral_bonuses (
  referred_id uuid primary key references public.experts(id) on delete cascade,
  paid_at timestamptz not null default now(),
  note text check (length(note) <= 500)
);
alter table public.referral_bonuses enable row level security;
drop policy if exists p_rb_admin on public.referral_bonuses;
create policy p_rb_admin on public.referral_bonuses for all using (public.is_admin()) with check (public.is_admin());

create or replace function public.admin_referrals()
returns table(referred_id uuid, referred_name text, referred_email text, referred_status text, referrer_name text, referrer_email text,
              code text, approved_hours numeric, paid_hours numeric, qualified boolean, bonus_paid_at timestamptz, created_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  return query
  select e.id, p.full_name, p.email, e.status, rp.full_name, rp.email, e.referred_by,
         coalesce((select sum(t.hours) from timesheets t where t.expert_id = e.id and t.status = 'approved'), 0),
         coalesce((select sum(po.hours) from payouts po where po.expert_id = e.id and po.status = 'paid'), 0),
         coalesce((select sum(po.hours) from payouts po where po.expert_id = e.id and po.status = 'paid'), 0) >= 10,
         rb.paid_at, e.created_at
  from experts e
  join profiles p on p.id = e.id
  left join experts r on lower(r.referral_code) = lower(e.referred_by) and r.id <> e.id
  left join profiles rp on rp.id = r.id
  left join referral_bonuses rb on rb.referred_id = e.id
  where coalesce(e.referred_by, '') <> ''
  order by e.created_at desc;
end $$;
revoke all on function public.admin_referrals() from public, anon;
grant execute on function public.admin_referrals() to authenticated;

create or replace function public.my_referrals() returns json
language sql stable security definer set search_path = public as $$
  with me as (select referral_code from experts where id = auth.uid()),
  refs as (
    select e.id,
           coalesce((select sum(po.hours) from payouts po where po.expert_id = e.id and po.status = 'paid'), 0) as hrs,
           exists (select 1 from referral_bonuses rb where rb.referred_id = e.id) as paid
    from experts e, me
    where me.referral_code is not null and lower(e.referred_by) = lower(me.referral_code) and e.id <> auth.uid()
  )
  select json_build_object('signed_up', count(*), 'qualified', count(*) filter (where hrs >= 10), 'paid', count(*) filter (where paid)) from refs;
$$;
revoke all on function public.my_referrals() from public, anon;
grant execute on function public.my_referrals() to authenticated;
